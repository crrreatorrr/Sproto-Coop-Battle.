// Concatenate the pure sim, CPU AI, and protocol into one classic script for
// Node, the browser, and goja. The bundle is not a mint path and not a host relay.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'build');
const bundlePath = path.join(outDir, 'coop-sim.js');
const pinPath = path.join(outDir, 'coop-sim.pin.json');
const parts = [
  'public/js/manifest.js',
  'public/js/sim.js',
  'public/js/ai.js',
  'public/js/net-protocol.js',
];

function sha256(buf) {
  return crypto.createHash('sha256').update(buf).digest('hex');
}

// Builds the bundle and pin in memory without writing anything. Tests use this to compare a
// fresh build with the committed build/coop-sim.js and build/coop-sim.pin.json.
export function composeServerSim() {
  const files = {};
  const body = [];
  for (const rel of parts) {
    const buf = fs.readFileSync(path.join(root, rel));
    files[path.basename(rel)] = sha256(buf);
    body.push(buf.toString('utf8'));
  }
  const banner = [
    '/* sproto-coop-battle server sim. Generated by scripts/build-server-sim.mjs. Do not edit. */',
    'var window = (typeof globalThis !== "undefined" ? globalThis : this);',
    'window.window = window;',
    '',
  ].join('\n');
  const bundle = banner + body.join('\n') + '\n';
  const sandbox = { console: { log() {} } };
  sandbox.globalThis = sandbox;
  sandbox.window = sandbox;
  vm.createContext(sandbox);
  vm.runInContext(bundle, sandbox, { filename: 'coop-sim.js' });
  if (!sandbox.Sim || !sandbox.Sim.exportState || !sandbox.SproAI || !sandbox.CoopProtocol || !sandbox.MANIFEST) {
    throw new Error('server bundle did not export Sim, SproAI, CoopProtocol, and MANIFEST');
  }
  const content = JSON.stringify(sandbox.CoopProtocol.contentManifest(sandbox.MANIFEST));
  const pin = {
    kind: 'sproto-coop-battle-sim-pin',
    gameId: 'sproto-coop-battle',
    protocolVersion: sandbox.CoopProtocol.PROTOCOL_VERSION,
    stateVersion: sandbox.Sim.STATE_VERSION,
    simHz: sandbox.CoopProtocol.LIMITS.simHz,
    loopHz: sandbox.CoopProtocol.LIMITS.loopHz,
    substeps: sandbox.CoopProtocol.LIMITS.substeps,
    snapshotHz: sandbox.CoopProtocol.LIMITS.snapshotHz,
    snapshotMaxHz: sandbox.CoopProtocol.LIMITS.snapshotMaxHz,
    files: files,
    bundleSha256: sha256(bundle),
    contentSha256: sha256(content),
    goja: 'github.com/dop251/goja v0.0.0-20261107161106-d6eaa50db8bc',
    node: '>=22',
  };
  return { bundlePath, pinPath, pin, bundle, pinText: JSON.stringify(pin, null, 2) + '\n' };
}

export function buildServerSim() {
  const built = composeServerSim();
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(bundlePath, built.bundle);
  fs.writeFileSync(pinPath, built.pinText);
  return { bundlePath, pinPath, pin: built.pin, bundle: built.bundle };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = buildServerSim();
  console.log(`bundle ${result.pin.bundleSha256}`);
  console.log(`content ${result.pin.contentSha256}`);
  console.log(`bytes ${fs.statSync(result.bundlePath).size}`);
}
