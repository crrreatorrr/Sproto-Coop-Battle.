#!/usr/bin/env python3
"""Measure alpha bounds of copied art and write public/js/manifest.js."""
from PIL import Image
import os, json
O = 'public/assets/'
POSES = 'art/fighter-poses/'
BOSSES = [
 ('01-marina-bront','Tidebreak Marina','Abyssal Salvager','Magnetic Crusher','#3a7bd5'),
 ('02-last-light-vela','Last Light Bar','Wrist Axe Walker','Twin Axe Press','#b04fd8'),
 ('03-mudline-crapto','Mudline Trenches','Trench Excavator','Canister Gantry','#7a6a3a'),
 ('04-ranch-zephyr','Sproto Ranch','Cursed Lantern','Haunted Harvest','#e07a26'),
 ('05-neon-sproto102','Neon Tomorrow','Ceramic Railwalker','Aegis Foundry','#22c3c9'),
 ('06-circuit-rune','Circuit Gate','Relay Breaker','Twinblade Ram','#4fd86a'),
 ('07-moonkeep-bigswole','Moonkeep Castle','Gatebreaker','High Citadel','#8a8fb8'),
 ('08-crown-alpha777','Crown Relay Chamber','Relay Bomb Loader','Jewel-Joust Rig','#e8c43a'),
 ('09-hatchery-highsproto','The Hatchery','Incubator Grabber','Brood Capture Rig','#d85a8a'),
 ('10-verse-sprotosales','Verse Gate','Scythe Duelist','Portal Interceptor','#6a5cff'),
 ('11-rooftop-sproto1668','Rooftop Breakaway','Rooftop Stalker','Raptor Siege Rig','#ff6a3a'),
 ('12-codebreak-sproto3106','Codebreak Ascent','Warrant Mecha','Summit Lockdown','#3affc8'),
]
# Calibrated collision and projectile-origin geometry is expressed in the original 256px space.
# Rendered sprite sheets change independently of the combat geometry.
with open(os.path.join(os.path.dirname(__file__), 'boss-combat-geometry.json'), encoding='utf-8') as f:
    boss_geometry = json.load(f)
bosses = []
for key, stage, m1, m2, color in BOSSES:
    phases = []
    if len(boss_geometry[key]) != 2:
        raise ValueError(f'{key} must have geometry for two phases')
    for p, geometry in zip(('p1', 'p2'), boss_geometry[key]):
        phases.append({
            'sheet': f'assets/bosses/{key}-{p}.webp',
            'proj': f'assets/bosses/{key}-{p}-projectiles.png',
            **geometry,
        })
    bosses.append({'key': key, 'stage': stage, 'machines': [m1, m2], 'color': color, 'pilot': key.split('-')[-1], 'phases': phases})
with open(os.path.join(os.path.dirname(__file__), 'sprotel-bitcoin.json'), encoding='utf-8') as f:
    bosses.append(json.load(f))
def hands(fid, fb):
    # Front-most opaque pixel in the arm band of each pose: where the weapon is held.
    out = []
    for i in range(32):
        im = Image.open(f'{POSES}{fid}/{i:02d}.png').convert('RGBA'); A = im.getchannel('A')
        bb = A.getbbox(); a = A.load(); top, bot = bb[1], bb[3]; h = bot - top; best = None
        for y in range(int(top + h*.30), int(top + h*.62)):
            for x in range(127, -1, -1):
                if a[x, y] > 100:
                    if best is None or x > best[0]: best = (x, y)
                    break
        out.append(list(best) if best else [(fb[0]+fb[2])//2 + 8, top + int(h*.45)])
    return out
fighters = []
for fid, name, color in [('sproto3106','Sproto Sheriff','#ff655e'),('vamp','VAMP','#5b83f4'),('guest09','Red Kev','#ff5a5a'),('guest10','Sprotel Bitcoin','#d9ccaa'),('rivet','Golden Sproto','#ffda55'),('dumpstar','Dumpstar','#77a9ff')]:
    im = Image.open(f'{POSES}{fid}/00.png').convert('RGBA')
    b = im.getchannel('A').getbbox()
    fighters.append({'id': fid, 'name': name, 'color': color, 'foot': [ (b[0]+b[2])//2, b[3] ], 'box': list(b), 'hands': hands(fid, b)})
with open(os.path.join(os.path.dirname(__file__), 'playable-roster.json'), encoding='utf-8') as f:
    roster = json.load(f)
for fighter in fighters:
    fighter.update(roster['originals'].get(fighter['id'], {}))
fighters.extend(roster['additions'])
with open(os.path.join(os.path.dirname(__file__), 'shadow-roster.json'), encoding='utf-8') as f:
    shadows = json.load(f)
roles = ['melee', 'ranged', 'twin']
shadows['stages'] = [[[row['id'], row['name'], roles.index(row['role'])] for row in stage]
                      for stage in shadows['stages']]
with open('public/js/manifest.js','w') as f:
    f.write('// Generated by tools/build-manifest.py — do not edit by hand.\n')
    f.write('window.MANIFEST=' + json.dumps({'bosses': bosses, 'fighters': fighters, 'shadows': shadows}, separators=(',',':')) + ';\n')
    f.write('for(const s of window.MANIFEST.shadows.stages)for(let i=0;i<s.length;i++){const [id,name,r]=s[i];s[i]={id,name,role:' +
            json.dumps(roles, separators=(',',':')) + '[r]};}\n')
print('ok', len(bosses), 'bosses')
