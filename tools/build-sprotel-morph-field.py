#!/usr/bin/env python3
"""Build standing Sprotel morph meshes, using the other bosses' mesh algorithm.

Run after pack-sprotel-bitcoin.py with Pillow, NumPy and OpenCV installed.
Only the Sprotel section is replaced; the original twelve boss fields stay intact.
"""
from base64 import b64encode
import importlib.util
import json
from pathlib import Path

import cv2
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('boss_fields', ROOT / 'tools/build-boss-morph-field.py')
base = importlib.util.module_from_spec(spec)
spec.loader.exec_module(base)
CELL, GRID = 176, 12
base.CELL, base.MAX_SHIFT = CELL, 28
base.GRID_AXIS = np.linspace(0, CELL - 1, GRID, dtype=np.float32)
base.GRID_X, base.GRID_Y = np.meshgrid(base.GRID_AXIS, base.GRID_AXIS)
POSES = [[0, 0, 0]] + [[0, 9 + i // 8, i % 8] for i in range(16)] + [[1, 0, 0]]
PAGE_ROWS = 5


def load_phase(number):
    # pack-sprotel-bitcoin.py writes the first five rows and the rest as separate pages.
    stem = ROOT / f'public/assets/bosses/13-last-call-sprotelbitcoin-p{number}'
    top = Image.open(stem.with_suffix('.webp')).convert('RGBA')
    lower = Image.open(stem.with_name(stem.name + '-lower.webp')).convert('RGBA')
    if top.size[1] != PAGE_ROWS * CELL or lower.size[0] != top.size[0]:
        raise ValueError(f'unexpected Sprotel page geometry for phase {number}')
    full = Image.new('RGBA', (top.size[0], top.size[1] + lower.size[1]))
    full.paste(top, (0, 0))
    full.paste(lower, (0, top.size[1]))
    return full


SHEETS = [load_phase(p) for p in (1, 2)]
CELS = [SHEETS[p].crop((col * CELL, row * CELL, (col + 1) * CELL, (row + 1) * CELL)) for p, row, col in POSES]


def guide(cel):
    # Cockpit is the fixed center; the bill/shoulder hinge moves separately.
    rgba = np.asarray(cel)
    y, x = np.mgrid[:CELL, :CELL]
    red = ((rgba[:, :, 0].astype(float) > rgba[:, :, 1] * 1.8) &
           (rgba[:, :, 0].astype(float) > rgba[:, :, 2] * 1.5) &
           (rgba[:, :, 0] > 135) & (rgba[:, :, 3] > 100) &
           (x > 55) & (x < 120) & (y > 25) & (y < 100))
    if not red.any():
        raise ValueError('missing pilot in transformation cel')
    pilot = [int(np.median(x[red])), int(np.median(y[red]))]
    return [pilot, [pilot[0] - 30, pilot[1] - 18]]


cv2.setNumThreads(1)
guides = [guide(cel) for cel in CELS]
features = [base.to_features(cel) for cel in CELS]
fields = []
for gap, ((source, source_alpha), (target, target_alpha)) in enumerate(zip(features, features[1:])):
    controls = [(guides[gap][0], guides[gap + 1][0], 20),
                (guides[gap][1], guides[gap + 1][1], 15)]
    outgoing, incoming = base.dense_flow(source, target), base.dense_flow(target, source)
    # Keep the early standing feet planted, then release the lower joints as
    # the legs interlock and lift into the curved tail.
    foot = 165 if gap < 6 else CELL + 28
    fields.extend((base.mesh(outgoing, incoming, source_alpha, controls, foot=foot, foot_taper=22),
                   base.mesh(incoming, outgoing, target_alpha, [(b, a, r) for a, b, r in controls],
                             foot=foot, foot_taper=22)))
content = b64encode(np.asarray(fields, dtype=np.int8).tobytes()).decode('ascii')
output = ROOT / 'public/js/boss-morph-field.js'
marker = '// Sprotel standing transformation: generated by tools/build-sprotel-morph-field.py.'
original = output.read_text().split(marker)[0].rstrip() + '\n'
output.write_text(original + marker + '\n' +
                  f"globalThis.CoopSprotelMorphField = '{content}';\n" +
                  f"globalThis.CoopSprotelMorphGuides = {json.dumps([guides], separators=(',', ':'))};\n")
print(f'Sprotel: {len(CELS)} standing keys, {len(fields)} directional meshes, {len(content)} base64 bytes')
